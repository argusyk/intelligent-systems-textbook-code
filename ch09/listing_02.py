# Наївний байєсівський фільтр небажаних повідомлень
from sklearn.feature_extraction.text import CountVectorizer
from sklearn.naive_bayes import MultinomialNB

train = [
    ("Вітаємо! Ви виграли iPhone, перейдіть за посиланням", "спам"),
    ("Термінова знижка 90 відсотків тільки сьогодні купуйте", "спам"),
    ("Ваш рахунок заблоковано, підтвердіть пароль за посиланням", "спам"),
    ("Отримайте кредит без довідок за 5 хвилин", "спам"),
    ("Безкоштовний приз чекає, натисніть тут", "спам"),
    ("Нагадую про лабораторну роботу в четвер о 10:00", "лист"),
    ("Надсилаю звіт з лабораторної роботи для перевірки", "лист"),
    ("Засідання кафедри перенесено на понеділок", "лист"),
    ("Розклад консультацій перед іспитом оновлено", "лист"),
    ("Підтвердіть участь у конференції до п'ятниці", "лист"),
]
texts, labels = zip(*train)
vec = CountVectorizer(lowercase=True)
# alpha=1: згладжування Лапласа
nb = MultinomialNB(alpha=1.0).fit(vec.fit_transform(texts), labels)

for msg in ["Ви виграли безкоштовний кредит, натисніть посилання",
            "Звіт з лабораторної надішлю до четверга",
            "Підтвердіть пароль до рахунку сьогодні"]:
    p = nb.predict_proba(vec.transform([msg]))[0]
    print(f"P(спам) = {p[list(nb.classes_).index('спам')]:.3f}  <- {msg}")
