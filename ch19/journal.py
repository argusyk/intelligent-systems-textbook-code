PATTERNS = {   # правила видобування: регулярні вирази
    "дата": r"\b\d{2}\.\d{2}\.\d{4}\b",
    "борт": r"\bUR-[A-Z]{3}\b",
    "P/N": r"P/N\s*([\w-]+)",
    "EGT, °C": r"EGT\s*(\d+)\s*°C",
    "тиск, бар": r"тиск[^\d]{0,20}(\d+,\d+)\s*бар",
    "вібрація, мм/с": r"вібрація[^\d]{0,10}(\d+,\d+)\s*мм/с",
}

def extract(text):
    out = {}
    for k, p in PATTERNS.items():
        m = re.search(p, text, flags=re.I)
        if m:
            out[k] = m.group(1) if m.groups() else m.group(0)
    return out

for text, _ in RECORDS[:4]:
    print(extract(text))

texts, labels = zip(*RECORDS)
clf = make_pipeline(TfidfVectorizer(analyzer="char_wb", ngram_range=(3, 5)), LogisticRegression(max_iter=2000))
acc = cross_val_score(clf, texts, labels, cv=5)
print(f"точність класифікації за розділом ATA (5-кратна перевірка): {acc.mean():.2f} +- {acc.std():.2f}")
clf.fit(texts, labels)
