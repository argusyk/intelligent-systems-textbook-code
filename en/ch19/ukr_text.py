APOSTROPHES = "'’ʼ`´‘"
HOMOGLYPHS = str.maketrans("aceiopxyAСEHIKMOPTXB", "асеіорхуАСЕНІКМОРТХВ")   # Latin -> Cyrillic

def normalize(text):
    text = re.sub(f"[{APOSTROPHES}]", "'", text)                    # a single kind of apostrophe
    # Latin letters inside Cyrillic words are replaced by their Cyrillic twins
    text = re.sub(r"\w+", lambda m: m.group(0).translate(HOMOGLYPHS)
                  if re.search("[а-яіїєґА-ЯІЇЄҐ]", m.group(0)) else m.group(0), text)
    return text.lower()

def stem(word, n=5):
    """A crude handling of word forms: the first n letters (термопару, термопари -> "термо")."""
    return word[:n] if len(word) > n else word

docs = [(sec, text) for sec, text in MANUAL.items()]
texts = [t for _, t in docs]
variants = {
    "words, no normalisation": dict(analyzer="word", lowercase=False),
    "normalisation": dict(analyzer="word", preprocessor=normalize),
    "normalisation + stems": dict(analyzer=lambda t: [stem(w) for w in re.findall(r"\w+", normalize(t))]),
    "character n-grams": dict(analyzer="char_wb", ngram_range=(3, 5), preprocessor=normalize),
}
queries = [(q, s) for q, s in TESTS] + [("Скільки тpиває пpомивка?", "49-30"),      # Latin "p"
                                        ("Опір термопари", "49-80"), ("ТИСК МАСЛА", "49-50")]
print(f"{'representation':26s} recall@1 (of {len(queries)} questions)")
for name, kw in variants.items():
    vec = TfidfVectorizer(**kw).fit(texts)
    D = vec.transform(texts)
    hits = sum(docs[int(np.argmax((D @ vec.transform([q]).T).toarray()))][0] == s for q, s in queries)
    print(f"{name:26s} {hits / len(queries):.2f}")
