# Сортування інцидентів у центрі моніторингу безпеки за коефіцієнтами впевненості
def combine(a, b):
    if a >= 0 and b >= 0: return a + b * (1 - a)
    if a < 0 and b < 0: return a + b * (1 + a)
    return (a + b) / (1 - min(abs(a), abs(b)))

RULES = [  # (умови, CF правила) для гіпотези «обліковий запис скомпрометовано»
    (["багато_невдалих_входів", "успішний_вхід_після_них"], 0.7),
    (["вхід_з_нової_країни"], 0.4),
    (["вхід_у_неробочий_час"], 0.2),
    (["привілейований_обліковий_запис"], 0.3),
    (["відомий_VPN_компанії"], -0.5),
    (["користувач_підтвердив_вхід_через_MFA"], -0.8),
]
ALERTS = {
    "INC-101": {"багато_невдалих_входів": 1.0, "успішний_вхід_після_них": 1.0, "вхід_з_нової_країни": 0.9,
                "привілейований_обліковий_запис": 1.0},
    "INC-102": {"вхід_з_нової_країни": 1.0, "вхід_у_неробочий_час": 1.0, "відомий_VPN_компанії": 1.0},
    "INC-103": {"багато_невдалих_входів": 0.8, "успішний_вхід_після_них": 0.6, "користувач_підтвердив_вхід_через_MFA": 1.0},
}
for inc, facts in ALERTS.items():
    cf = 0.0
    for conds, r in RULES:
        e = min(facts.get(c, 0.0) for c in conds)
        if e > 0.2:
            cf = combine(cf, e * r)
    level = "КРИТИЧНИЙ" if cf >= 0.6 else ("перевірити" if cf >= 0.2 else "закрити")
    print(f"{inc}: CF = {cf:+.2f} -> {level}")
