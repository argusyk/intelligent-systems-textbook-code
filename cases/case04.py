# Граф знань освітньої програми: пререквізити, успадкування й запити
import networkx as nx

G = nx.DiGraph()
prereq = [("Математика", "Дискретна математика"), ("Дискретна математика", "Інтелектуальні системи"),
          ("Інформатика", "Програмування"), ("Програмування", "Інтелектуальні системи"),
          ("Математика", "Теорія ймовірностей"), ("Теорія ймовірностей", "Інтелектуальні системи"),
          ("Інтелектуальні системи", "Машинне навчання в інженерії")]
G.add_edges_from(prereq, rel="пререквізит")
kind = {"Математика": "фундаментальна", "Інформатика": "фундаментальна",
        "Дискретна математика": "фундаментальна", "Теорія ймовірностей": "фундаментальна",
        "Програмування": "професійна", "Інтелектуальні системи": "вибіркова",
        "Машинне навчання в інженерії": "вибіркова"}
nx.set_node_attributes(G, kind, "тип")

target = "Інтелектуальні системи"
print("треба вивчити до курсу:", sorted(nx.ancestors(G, target)))
print("курс відкриває доступ до:", sorted(nx.descendants(G, target)))
print("рекомендований порядок:", list(nx.topological_sort(G)))
print("цикли у плані:", list(nx.simple_cycles(G)) or "немає")
