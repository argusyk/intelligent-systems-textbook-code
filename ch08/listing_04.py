# Планування в стилі STRIPS: заміна стартера ДСУ. Стан – множина фактів, дія має
# передумови, список додавання та список вилучення; план шукаємо пошуком у ширину.
from collections import deque

ACTIONS = {  # назва: (передумови, додати, вилучити)
    "знеструмити ДСУ":       ({"живлення"}, {"знеструмлено"}, {"живлення"}),
    "відкрити капот":        (set(), {"капот відкрито"}, {"капот закрито"}),
    "від'єднати проводку":   ({"знеструмлено", "капот відкрито", "проводка під'єднана"},
                              {"проводка від'єднана"}, {"проводка під'єднана"}),
    "зняти стартер":         ({"проводка від'єднана", "старий стартер"}, {"стартер знято"},
                              {"старий стартер"}),
    "встановити стартер":    ({"стартер знято", "новий стартер на складі"}, {"новий стартер"},
                              {"стартер знято", "новий стартер на складі"}),
    "під'єднати проводку":   ({"новий стартер", "проводка від'єднана"},
                              {"проводка під'єднана"},
                              {"проводка від'єднана"}),
    "закрити капот":         ({"капот відкрито"}, {"капот закрито"}, {"капот відкрито"}),
    "подати живлення":       ({"знеструмлено", "капот закрито"}, {"живлення"},
                              {"знеструмлено"}),
    "пробний запуск":        ({"живлення", "новий стартер", "проводка під'єднана",
                               "капот закрито"},
                              {"запуск перевірено"}, set()),
}
START = frozenset({"живлення", "капот закрито", "проводка під'єднана", "старий стартер",
                   "новий стартер на складі"})
GOAL = {"запуск перевірено", "капот закрито"}

def plan(start, goal):
    queue, seen, expanded = deque([(start, [])]), {start}, 0
    while queue:
        state, steps = queue.popleft(); expanded += 1
        if goal <= state:
            return steps, expanded
        for name, (pre, add, rem) in ACTIONS.items():
            if pre <= state:
                nxt = frozenset((state - rem) | add)
                if nxt not in seen:
                    seen.add(nxt); queue.append((nxt, steps + [name]))
    return None, expanded

steps, n = plan(START, GOAL)
print(f"розкрито станів: {n}; кроків плану: {len(steps)}")
for i, a in enumerate(steps, 1):
    print(f"{i}. {a}")
