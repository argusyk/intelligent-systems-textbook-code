# Рушій бізнес-правил: допуск до сесії та стипендія (зворотне виведення з поясненням)
RULES = {
    "допуск_до_сесії": [["усі_лабораторні_захищено", "немає_фінансового_боргу"]],
    "стипендія": [["допуск_до_сесії", "середній_бал_не_нижче_4", "немає_перескладань"],
                  ["допуск_до_сесії", "соціальна_пільга", "немає_перескладань"]],
}
FACTS = {"усі_лабораторні_захищено": True, "немає_фінансового_боргу": True,
         "середній_бал_не_нижче_4": False, "соціальна_пільга": True,
         "немає_перескладань": True}

def prove(goal, depth=0):
    pad = "  " * depth
    if goal in FACTS:
        print(f"{pad}{goal}: {'так' if FACTS[goal] else 'ні'} (факт)")
        return FACTS[goal]
    for i, conds in enumerate(RULES.get(goal, []), 1):
        print(f"{pad}{goal}: пробую варіант {i}")
        if all(prove(c, depth + 1) for c in conds):
            print(f"{pad}=> {goal} доведено варіантом {i}")
            return True
    print(f"{pad}=> {goal} не доведено")
    return False

prove("стипендія")
