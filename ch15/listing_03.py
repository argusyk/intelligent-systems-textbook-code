# Скільки інвестувати в кібербезпеку: гра з природою (витрати за рік, тис. грн)
import numpy as np

acts = ["мінімальний захист", "базовий захист", "повний захист + SOC"]
states = ["атак немає", "масова атака", "цільова атака"]
C = np.array([[20, 300, 1500],
              [120, 160, 700],
              [400, 410, 480]], float)
q = np.array([0.5, 0.4, 0.1])                                # оцінка ймовірностей експертами

res = {"Байєса": C @ q, "Лапласа": C.mean(1), "Вальда": C.max(1),
       "Севіджа": (C - C.min(0)).max(1), "Гурвіца (0,5)": 0.5 * C.max(1) + 0.5 * C.min(1)}
for k, v in res.items():
    print(f"{k:14s} {v.round(0)} -> {acts[int(v.argmin())]}")
for p3 in (0.1, 0.3, 0.5, 0.55):  # чутливість до ймовірності цільової атаки
    qq = np.array([0.6 - p3, 0.4, p3])
    print(f"P(цільова) = {p3:.2f}: за Байєсом -> {acts[int((C @ qq).argmin())]}")
