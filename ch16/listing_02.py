import anthropic

# фрагменти бази знань, які знайшов етап пошуку (сам пошук показано в кейсі 16.9 і підрозділі 17.8)
FOUND = [
    "R5: перегрів разом із затяжним запуском свідчить про погане "
    "розпилення палива форсунками.",
    "R12: підвищена витрата палива за нормальних обертів характерна "
    "для забруднених форсунок.",
    "R13: після промивки форсунок гіпотеза H1 малоймовірна протягом 50 год напрацювання.",
    "Процедура: промивка форсунок на крилі, тривалість близько 4 год, "
    "див. керівництво розд. 49-30.",
]
diagnosis = "H1 (забруднені форсунки), CF = 0,85; спрацювали правила R5 і R12"
context = "\n".join(FOUND)

client = anthropic.Anthropic()
resp = client.messages.create(
    model="claude-opus-4-8",
    max_tokens=600,
    system=("Ти пояснюєш техніку ТО висновок експертної системи. Використовуй лише наведені "
            "фрагменти бази знань. Не змінюй діагноз і не додавай фактів від себе."),
    messages=[{"role": "user",
               "content": f"Висновок системи: {diagnosis}\n\n"
                          f"Фрагменти бази знань:\n{context}\n\n"
                          "Поясни коротко, чому система дійшла такого висновку "
                          "і що перевірити першим."}],
)
print("".join(b.text for b in resp.content if b.type == "text"))
