# Item-based рекомендація наступної перевірки ДСУ за історією спільних перевірок у журналі ТО
import numpy as np

CHECKS = ["термопара", "форсунки", "паливний фільтр", "регулятор", "стартер", "акумулятор", "масляний фільтр", "підшипник"]
CASES = [  # набори перевірок, виконаних в одному зверненні
    {"термопара", "форсунки", "паливний фільтр"}, {"термопара", "форсунки"}, {"форсунки", "регулятор"},
    {"термопара", "форсунки", "регулятор"}, {"стартер", "акумулятор"}, {"стартер", "акумулятор"},
    {"масляний фільтр", "підшипник"}, {"масляний фільтр", "підшипник", "форсунки"}, {"паливний фільтр", "регулятор"},
    {"термопара", "паливний фільтр"}, {"стартер", "акумулятор", "паливний фільтр"}, {"форсунки", "паливний фільтр"},
]
M = np.array([[c in case for c in CHECKS] for case in CASES], float)     # звернення x перевірки
norm = np.linalg.norm(M, axis=0) + 1e-9
S = (M.T @ M) / np.outer(norm, norm)                                      # косинусна подібність перевірок
np.fill_diagonal(S, 0)

def recommend(done, k=3):
    idx = [CHECKS.index(c) for c in done]
    score = S[idx].sum(axis=0)
    score[idx] = -1                                                       # не радити вже виконане
    return [(CHECKS[i], round(float(score[i]), 2)) for i in np.argsort(score)[::-1][:k]]

for done in [["термопара"], ["стартер"], ["масляний фільтр"]]:
    print(f"після {done}: {recommend(done)}")
