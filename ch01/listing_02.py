# Профіль «інтелектуальності» реальних систем за п'ятьма властивостями розділу 1.3
PROPS = ["знання", "невизначеність", "пояснення", "навчання", "адаптивність"]
SYSTEMS = {  # 0 – немає, 1 – частково, 2 – виражено
    "спам-фільтр пошти":          [0, 2, 0, 2, 2],
    "автомобільний навігатор":    [1, 1, 1, 0, 1],
    "банківський кредитний скоринг": [1, 2, 1, 2, 1],
    "експертна система MYCIN":    [2, 2, 2, 0, 0],
    "голосовий асистент на LLM":  [1, 2, 1, 2, 2],
}
print(f"{'система':32s}" + "".join(f"{p[:6]:>8s}" for p in PROPS) + "   сума")
for name, v in sorted(SYSTEMS.items(), key=lambda kv: -sum(kv[1])):
    print(f"{name:32s}" + "".join(f"{x:8d}" for x in v) + f"   {sum(v):4d}")
weak = [p for i, p in enumerate(PROPS) if all(v[i] < 2 for v in SYSTEMS.values())]
print("властивості, яких бракує всім системам:", weak or "немає")
