# Експертна система служби ІТ-підтримки університету: пряме виведення з поясненням
RULES = [  # (ім'я, пріоритет, умови, висновок, пояснення для користувача)
    ("W1", 10, {"немає_wifi", "інші_пристрої_працюють"}, "проблема_пристрою",
     "інші пристрої працюють, отже мережа доступна"),
    ("W2", 10, {"немає_wifi", "інші_пристрої_не_працюють"}, "збій_точки_доступу",
     "не працює жоден пристрій у приміщенні"),
    ("W3", 5,  {"проблема_пристрою", "пароль_змінювали"}, "порада:_ввести_новий_пароль",
     "пароль до мережі змінювали, а пристрій зберіг старий"),
    ("W4", 1,  {"проблема_пристрою"}, "порада:_перезавантажити_мережевий_адаптер",
     "типова причина – завислий адаптер"),
    ("W5", 10, {"збій_точки_доступу"}, "заявка:_черговому_адміністратору",
     "потрібне втручання адміністратора мережі"),
    ("M1", 10, {"не_входить_у_moodle", "пошта_працює"}, "порада:_скинути_пароль_moodle",
     "обліковий запис активний, проблема лише в Moodle"),
]

def infer(facts):
    wm, trace = set(facts), []
    while True:
        cand = [r for r in RULES if r[2] <= wm and r[3] not in wm]
        if not cand:
            return wm, trace
        r = max(cand, key=lambda r: (r[1], len(r[2])))      # пріоритет, потім специфічність
        wm.add(r[3]); trace.append(r)

wm, trace = infer({"немає_wifi", "інші_пристрої_працюють", "пароль_змінювали"})
for name, _, cond, concl, why in trace:
    print(f"{name}: {concl}  (бо {why})")
print("рекомендації:", sorted(f for f in wm if f.startswith(("порада", "заявка"))))
