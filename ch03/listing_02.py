# Аналіз репертуарної решітки Келлі: оцінки експертом несправностей ДСУ за конструктами
import numpy as np

elements = ["форсунки", "паливний фільтр", "стартер", "термопара", "підшипник",
            "масляний насос"]
constructs = [("перегрів", "нормальна EGT"), ("затяжний запуск", "нормальний запуск"),
              ("висока витрата", "нормальна витрата"), ("вібрація", "без вібрації"),
              ("падіння тиску масла", "тиск у нормі"), ("розвивається поступово",
                                                        "виникає раптово")]
# оцінки 1..5: 1 – ближче до лівого полюса конструкта, 5 – до правого
G = np.array([[1, 2, 5, 5, 3],    # перегрів ... нормальна EGT
              [1, 1, 1, 5, 5],    # затяжний запуск ...
              [1, 4, 5, 5, 5],    # висока витрата ...
              [5, 5, 5, 5, 1],    # вібрація ...
              [5, 5, 5, 5, 2],    # падіння тиску масла ...
              [1, 2, 3, 4, 2]])   # поступово ... раптово
G = np.column_stack([G, [5, 5, 5, 3, 1, 1]])     # масляний насос
D = np.abs(G[:, :, None] - G[:, None, :]).sum(0)  # відстань між несправностями
iu = np.triu_indices(len(elements), 1)
pairs = sorted(zip(D[iu], iu[0], iu[1]))[:3]
print("найважче розрізнити (мала відстань):")
for d, i, j in pairs:
    diff = [constructs[k][0] for k in range(len(constructs)) if abs(G[k, i] - G[k, j]) >= 2]
    print(f"  {elements[i]} - {elements[j]}: відстань {d}; "
          f"розрізняє: {diff or 'немає конструкта'}")
R = np.corrcoef(G)
k1, k2 = np.unravel_index(np.argmax(np.abs(R - np.eye(len(R)))), R.shape)
print(f"найбільш пов'язані конструкти: «{constructs[k1][0]}» і «{constructs[k2][0]}», r = "
      f"{R[k1, k2]:.2f}")
