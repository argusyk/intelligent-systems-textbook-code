import pandas as pd
from sklearn.tree import DecisionTreeClassifier, export_text

rows = [
    ("висока","затяжний","висока","норма","так"), ("висока","затяжний","норма","норма","так"),
    ("висока","нормальний","висока","норма","так"),
    ("висока","нормальний","норма","висока","ні"),
    ("підвищена","затяжний","висока","норма","так"),
    ("підвищена","затяжний","норма","висока","ні"),
    ("підвищена","нормальний","висока","норма","так"),
    ("підвищена","нормальний","норма","норма","ні"),
    ("норма","затяжний","норма","норма","ні"), ("норма","затяжний","висока","норма","так"),
    ("норма","нормальний","норма","висока","ні"), ("норма","нормальний","норма","норма","ні"),
    ("висока","затяжний","висока","висока","так"),
    ("норма","нормальний","висока","висока","ні"),
]
df = pd.DataFrame(rows, columns=["egt", "start", "fuel", "vib", "fault"])
enc = {"норма": 0, "підвищена": 1, "висока": 2, "нормальний": 0, "затяжний": 1}
X = df[["egt", "start", "fuel", "vib"]].replace(enc)
clf = DecisionTreeClassifier(criterion="entropy", max_depth=3, random_state=0)
clf.fit(X, df["fault"])
print(export_text(clf, feature_names=list(X.columns)))
